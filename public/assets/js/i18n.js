const dictionaries = { en: {}, da };

export function t(key, params) {
  const dict = dictionaries[store.prefs.locale] || {};
  let str = dict[key] !== undefined ? dict[key] : key;
  if (params) {
    Object.entries(params).forEach(([k, v]) => { str = str.split(`{${k}}`).join(String(v)); });
  }
  return str;
}

export function locale() {
  return store.prefs.locale === 'da' ? 'da-DK' : 'en-GB';
}
